import { describe, expect, it } from 'vitest'
import { strFromU8, unzipSync } from 'fflate'
import { createXlsxBlob } from './xlsx-export'
import { parseXlsxRows, rowsFromHeader } from './xlsx-import'

describe('XLSX import', () => {
  it('reads a report generated by CloudTool and finds its header row', async () => {
    const blob = createXlsxBlob(
      ['SERVER ID', 'SERVER NAME', 'CURRENT IP', 'NEW IP ADDRESS'],
      [['server-1', 'Web 1', '10.0.0.2', '10.0.0.10']],
      {
        title: 'ATTACH PRIVATE IP TEMPLATE',
        metadata: [{ label: 'Instructions', value: 'Enter a new IP.' }],
      }
    )
    const rows = parseXlsxRows(await blob.arrayBuffer())
    const records = rowsFromHeader(rows, ['SERVER ID', 'NEW IP ADDRESS'])

    expect(records).toEqual([
      {
        'SERVER ID': 'server-1',
        'SERVER NAME': 'Web 1',
        'CURRENT IP': '10.0.0.2',
        'NEW IP ADDRESS': '10.0.0.10',
      },
    ])
  })

  it('writes conditional and required Excel validations', async () => {
    const blob = createXlsxBlob(
      ['RESOURCE TYPE', 'NAME', 'REGION'],
      [['VPC', 'app-vpc', 'vn-central-1']],
      {
        validations: [
          {
            header: 'RESOURCE TYPE',
            values: ['VPC', 'SUBNET'],
            allowBlank: false,
          },
          {
            header: 'NAME',
            values: [],
            type: 'custom',
            allowBlank: false,
            formula: 'LEN(TRIM({cell}))>0',
          },
          {
            header: 'REGION',
            values: ['vn-central-1'],
            allowBlank: false,
            enabledWhen: { header: 'RESOURCE TYPE', values: ['VPC'] },
          },
        ],
      }
    )
    const files = unzipSync(new Uint8Array(await blob.arrayBuffer()))
    const worksheet = strFromU8(files['xl/worksheets/sheet1.xml'])

    expect(worksheet).toContain('type="custom"')
    expect(worksheet).toContain('LEN(TRIM(B2))&gt;0')
    expect(worksheet).toContain('IF($A2=&quot;VPC&quot;')
    expect(worksheet).toContain('allowBlank="0"')
  })
})
